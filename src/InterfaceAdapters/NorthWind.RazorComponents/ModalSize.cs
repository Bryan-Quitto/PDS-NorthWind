namespace NorthWind.RazorComponents;

/// <summary>
/// Define las dimensiones disponibles para el componente ModalDialog según Bootstrap 5.
/// </summary>
public enum ModalSize
{
    /// <summary>
    /// Modal estándar (sin clase de tamaño adicional).
    /// </summary>
    Medium = 0,

    /// <summary>
    /// Modal pequeño (.modal-sm).
    /// </summary>
    Small = 1,

    /// <summary>
    /// Modal grande (.modal-lg).
    /// </summary>
    Large = 2,

    /// <summary>
    /// Modal extra grande (.modal-xl).
    /// </summary>
    ExtraLarge = 3
}
